class MarkdownReportBuilder:
    def __init__(self, case_dir):
        self.case_dir = case_dir
        self.evidence = []
        self.timeline = []
        self.iocs = defaultdict(set)
        self.behaviors = defaultdict(list)
        self.hard_iocs = defaultdict(set)
        self.soft_iocs = defaultdict(set)
        self.environmental = set()
        self.state_changes = {
            "filesystem": [],
            "registry": []
        }

    def generate_executive_summary(self, case_score):
        sev = case_score["severity"]
        conf = case_score["confidence"]
        #reasons = "; ".join(case_score["rationale"][:3])

        reasons = ""
        for r in case_score["rationale"]:
            reasons += f"- {r}\n"

        return (
            f"This report presents the forensic analysis results generated by "
            f"**GhostRun**, a behavioral forensic sandbox.\n"
            f"The analysis is based on offline reconstruction of evidence collected "
            f"during sample execution.\n"
            f"This analysis identified malicious activity with an overall severity of **{sev}** "
            f"and a confidence level of **{conf}**.\n"
            f"The assessment is based on observed system state changes and runtime behavior,\n"
            f"including: \n{reasons}"
        )

    def calculate_case_severity_confidence(self, fs_summary, reg_summary, behaviors, soft_iocs):        
        severity_score = 0
        confidence_score = 0
        rationale = []

        # ---------------- SEVERITY (IMPACT) ----------------
        if fs_summary["ext_changes"]:
            severity_score += 5
            rationale.append("Mass filesystem state changes observed (file extension changes)")

        if fs_summary["modified"] >= 5:
            severity_score += 2
            rationale.append(f"Multiple files modified ({fs_summary['modified']} files)")

        if reg_summary["values_modified"]:
            severity_score += 3
            rationale.append("Registry values modified with before/after evidence")

        #if any("self-delete" in b.lower() for b in behaviors.get("Process", [])):
        #    severity_score += 2
        #    rationale.append("Anti-forensic behavior detected (self-deletion)")

        # ---------------- PROCESS / ANTI-FORENSIC ----------------
        process_findings = behaviors.get("Process", [])

        if any("self-deletion" in p.lower() or "anti-forensic" in p.lower() for p in process_findings):
            severity_score += 2
            confidence_score += 2
            rationale.append("Anti-forensic behavior observed (self-deletion)")

        # ---------------- NETWORK BEHAVIOR ----------------
        network_findings = behaviors.get("Network", [])

        for n in network_findings:
            nl = n.lower()

            if "discord" in nl or "telegram" in nl:
                severity_score += 2
                confidence_score += 2
                rationale.append(
                    "Outbound network connection to cloud messaging service (Discord/Telegram abuse)"
                )

            elif "outbound connection" in nl:
                severity_score += 1
                confidence_score += 1
                rationale.append(
                    "Outbound network activity observed during execution"
                )
            elif "outbound network connection" in nl:
                severity_score += 1
                confidence_score += 1
                rationale.append(
                    "Outbound connection attempt to external IP observed during execution"
                )

        # ---------------- CONFIDENCE (CERTAINTY) ----------------
        if fs_summary["ext_changes"]:
            confidence_score += 3  # snapshot-driven = strong
        if reg_summary["values_modified"]:
            confidence_score += 3  # explicit before/after
        if behaviors:
            confidence_score += 2  # correlated runtime behavior

        executed = soft_iocs.get("Executed Malware", set())
        if executed:
            severity_score += 1
            confidence_score += 1
            rationale.append("Malicious executable executed in user context")


        # ---------------- MAP SCORE ----------------
        if severity_score >= 7:
            severity = "High"
        elif severity_score >= 4:
            severity = "Medium"
        else:
            severity = "Low"

        if confidence_score >= 6:
            confidence = "High"
        elif confidence_score >= 3:
            confidence = "Medium"
        else:
            confidence = "Low"

        return {
            "severity": severity,
            "confidence": confidence,
            "rationale": rationale
        }

    def fmt_ts(self, ts):
        if isinstance(ts, str):
            return ts
        return ts.strftime("%Y-%m-%d %H:%M:%S UTC")

    def normalize_blob(self, val):
        """
        Convert registry before/after value into bytes if possible
        """
        if val is None:
            return None

        if isinstance(val, bytes):
            return val

        # from string like "b'\\x00\\x01...'"
        if isinstance(val, str) and val.startswith("b'"):
            try:
                return eval(val)
            except Exception:
                return None

        return None

    def render_wallpaper_section(self):
        lines = []
        lines.append("### Desktop Wallpaper Changes\n")

        found = False

        for ev in self.evidence:
            if ev.get("category") != "registry_raw":
                continue

            data = ev.get("data", {})
            key = data.get("key", "")
            value_name = data.get("value_name", "")

            if value_name != "TranscodedImageCache":
                continue

            before_blob = self.normalize_blob(data.get("before"))
            after_blob = self.normalize_blob(data.get("after"))

            wp_before = extract_wallpaper_path(before_blob)
            wp_after = extract_wallpaper_path(after_blob)

            found = True

            lines.append(f"- Registry Path: `{key}\\{value_name}`")
            lines.append(f"- Before: `{wp_before}`")
            lines.append(f"- After : `{wp_after}`")

            if wp_before != wp_after:
                lines.append(
                    "Interpretation: Desktop wallpaper was modified. "
                    "This represents a visual user-impact artifact and "
                    "does not by itself indicate code execution.\n"
                )
            else:
                lines.append(
                    "Interpretation: Wallpaper cache updated without "
                    "an observable change in image path.\n"
                )

        if not found:
            lines.append("_No desktop wallpaper artifacts observed._\n")

        return "\n".join(lines)

    def render_userassist_section(self, registry_events):
        lines = []
        lines.append("### UserAssist Execution Artifacts\n")

        found = False

        for ev in registry_events:
            data = ev.get("data", {})
            key = data.get("key") or data.get("key_path", "")
            value_name = data.get("value_name", "")

            if "UserAssist" not in key or not value_name:
                continue

            found = True

            decoded = decode_userassist(value_name)

            conf_score = confidence_score(decoded["confidence"])
            severity = calculate_severity(
                ioc_type="execution" if decoded["category"] == "execution" else "static",
                impact="user",
                confidence=conf_score
            )

            lines.append(f"- Registry Path : `{key}`")
            lines.append(f"- Raw Value     : `{value_name}`")
            lines.append(f"- Decoded Value : `{decoded['decoded']}`")
            lines.append(f"- Category      : {decoded['category']}")
            lines.append(f"- Confidence    : {decoded['confidence']}")
            lines.append(f"- Severity      : {severity}")
            lines.append(f"- Name Interpretation : {decoded['explanation']}\n")

            before_blob = self.normalize_blob(data.get("before"))
            after_blob = self.normalize_blob(data.get("after"))

            parsed_before = parse_userassist_binary(before_blob) if before_blob else {}
            parsed_after = parse_userassist_binary(after_blob) if after_blob else {}
            #print(f"parsed_before: {parsed_before}")
            #print(f"parsed_after: {parsed_after}")
            
            if parsed_before and parsed_after:
                interpretation = interpret_userassist(parsed_before, parsed_after)
            else:
                interpretation = {
                    "confidence": "info",
                    "explanation": "UserAssist binary data not available or could not be parsed"
                }

            lines.append(f"- Run Count (before → after): "
                         f"{parsed_before.get('run_count')} → {parsed_after.get('run_count')}")

            lines.append(f"- Last Execution Time: {parsed_after.get('last_execution_time')}")
            lines.append(f"- Interpretation: {interpretation['explanation']}")
            lines.append(f"- Binary Interpretation : {interpretation['explanation']}")
            lines.append(f"- Binary Confidence     : {interpretation['confidence']}\n")            

        if not found:
            lines.append("_No UserAssist execution artifacts observed._\n")

        return "\n".join(lines)

    def render_registry_changes(self, registry_changes):
        lines = []
        lines.append("## Observed Registry Changes\n")

        for c in registry_changes:
            lines.append(f"- Path  : `{c['path']}`")
            lines.append(f"- Name  : `{c['value_name']}`")
            lines.append(f"- Before: `{c.get('before')}`")
            lines.append(f"- After : `{c.get('after')}`\n")

        if len(lines) == 1:
            lines.append("_No registry changes observed._\n")

        return "\n".join(lines)

    def render_filesystem_changes(self, fs_changes):
        lines = []
        lines.append("## Observed Filesystem Changes\n")

        for f in fs_changes:
            lines.append(f"- Path : `{f['path']}`")
            lines.append(f"- Type : {f['change_type']}")
            lines.append(f"- Time : {self.fmt_ts(f['timestamp'])}")

        if len(lines) == 1:
            lines.append("_No filesystem changes observed._\n")

        return "\n".join(lines)

    def summarize_state_changes(self):
        fs_summary = {
            "created": 0,
            "deleted": 0,
            "modified": 0,
            "ext_changes": []
        }

        reg_summary = {
            "keys_added": set(),
            "values_added": [],
            "values_modified": []
        }

        # ---- Filesystem ----
        for ev in self.state_changes["filesystem"]:
            evt = ev.get("event")
            data = ev.get("data", {})

            if evt == "file_created":
                fs_summary["created"] += 1

            elif evt == "file_deleted":
                fs_summary["deleted"] += 1

            elif evt == "file_modified":
                fs_summary["modified"] += 1

            elif evt == "mass_extension_change":
                fs_summary["ext_changes"].append({
                    "from": data.get("from_ext"),
                    "to": data.get("to_ext"),
                    "count": data.get("affected_files"),
                    "root": data.get("root")
                })

        # ---- Registry ----
        for ev in self.state_changes["registry"]:
            evt = ev.get("event")
            data = ev.get("data", {})

            if evt in ("key_added", "value_added"):
                key = data.get("key") or data.get("key_path")
                if key:
                    reg_summary["keys_added"].add(key)

                if data.get("value_name"):
                    reg_summary["values_added"].append(
                        f"{key}\\{data.get('value_name')}"
                    )
            elif evt == "value_modified":
                key = data.get("key")
                name = data.get("value_name")
                before = data.get("before")
                after = data.get("after")

                if key and name:
                    reg_summary["values_modified"].append({
                        "key": key,
                        "value": name,
                        "before": before,
                        "after": after
                    })               

        return fs_summary, reg_summary
        

    # --------------------------------------------------
    # LOAD EVIDENCE
    # --------------------------------------------------
    def load_evidence(self):
        # one shared, append-only evidence.jsonl per case now (see
        # receiver_http.py/sender_http.py), not a directory of individual
        # per-event .json files. a malformed line (e.g. truncated by a
        # crash mid-write) is skipped without losing every line after it,
        # unlike the old per-file loader where one bad file just vanished
        # silently on its own.
        jsonl_path = os.path.join(self.case_dir, "evidence.jsonl")
        if not os.path.exists(jsonl_path):
            return

        with open(jsonl_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    self.evidence.append(json.loads(line))
                except Exception:
                    continue

    # --------------------------------------------------
    # BUILD TIMELINE
    # --------------------------------------------------
    def build_timeline(self):
        self.timeline = sorted(
            self.evidence,
            key=lambda e: e.get("timestamp", "")
        )

