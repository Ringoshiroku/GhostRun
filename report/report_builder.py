    def render(self):
        lines = []
        
        fs_summary, reg_summary = self.summarize_state_changes()
        case_score = self.calculate_case_severity_confidence(
            fs_summary,
            reg_summary,
            self.behaviors,
            self.soft_iocs
        )

        # Title
        lines.append("# GhostRun Forensic Analysis Report\n")

        # Metadata
        lines.append("## Case Information\n")
        lines.append(f"- Case Directory: `{self.case_dir}`")
        lines.append(f"- Total Evidence Items: {len(self.evidence)}\n")

        # Executive Summary
        summary = self.generate_executive_summary(case_score)
        lines.append("## Executive Summary\n")
        lines.append(summary + "\n")

        '''
        lines.append("## Executive Summary\n")
        lines.append(
            "This report presents the forensic analysis results generated by "
            "**GhostRun**, a behavioral forensic sandbox. "
            "The analysis is based on offline reconstruction of evidence collected "
            "during sample execution.\n"
            "The analysis identified observable system state changes following execution, "
            "including filesystem and registry modifications, which are consistent with "
            "malicious behavior.\n"
        )
        '''
        
        # Timeline
        #lines.append("## Timeline of Events\n")
        #for ev in self.timeline:
        #    ts = ev.get("timestamp")
        #    cat = ev.get("category")
        #    evt = ev.get("event")
        #    lines.append(f"- **{ts}** — `{cat}:{evt}`")
        #lines.append("")

        # Findings
        lines.append("## Key Findings\n")
        for ev in self.timeline:
            if ev.get("confidence") == "high":
                lines.append(
                    f"- **{ev.get('event')}** ({ev.get('category')}) — "
                    f"{ev.get('data')}"
                )
        lines.append("")

        # --------------------------------------------------
        # OBSERVED STATE CHANGES (SNAPSHOT-DRIVEN)
        # --------------------------------------------------
        lines.append("## Observed State Changes (Snapshot-Based)\n")

        # ---- Filesystem ----
        lines.append("### Filesystem State Changes\n")
        if (
            fs_summary["created"] == 0
            and fs_summary["deleted"] == 0
            and fs_summary["modified"] == 0
            and not fs_summary["ext_changes"]
        ):
            lines.append("_No significant filesystem state changes observed._\n")
        else:
            if fs_summary["created"]:
                lines.append(f"- Files created: **{fs_summary['created']}**")
            if fs_summary["deleted"]:
                lines.append(f"- Files deleted: **{fs_summary['deleted']}**")
            if fs_summary["modified"]:
                lines.append(f"- Files modified: **{fs_summary['modified']}**")

            for ec in fs_summary["ext_changes"]:
                lines.append(
                    f"- Mass extension change under **{ec.get('root')}**: "
                    f"`{ec.get('from')}` → `{ec.get('to')}` "
                    f"({ec.get('count')} files)"
                )
            lines.append("")

        # ---- Registry ----
        lines.append("### Registry State Changes\n")
        if (
            not reg_summary["keys_added"]
            and not reg_summary["values_added"]
            and not reg_summary["values_modified"]
        ):
            lines.append("_No significant registry state changes observed._\n")
        else:
            if reg_summary["keys_added"]:
                lines.append("- Registry keys added:")
                for k in sorted(reg_summary["keys_added"]):
                    lines.append(f"  - `{k}`")

            if reg_summary["values_added"]:
                lines.append("- Registry values added:")
                for v in reg_summary["values_added"]:
                    lines.append(f"  - `{v}`")

            if reg_summary["values_modified"]:
                lines.append("- Registry values modified:")
                for m in reg_summary["values_modified"]:
                    lines.append(
                        f"  - `{m['key']}\\{m['value']}`\n"
                        f"    - Before: `{m['before']}`\n"
                        f"    - After : `{m['after']}`"
                    )

        lines.append("")

        # ---- UserAssist Interpretation ----
        lines.append(self.render_userassist_section(self.state_changes["registry"]))
        lines.append("")

        # ---- Desktop Wallpaper Changes ----
        lines.append(self.render_wallpaper_section())
        lines.append("")

        # IOC Section
        lines.append("## Indicators of Compromise (IOCs)\n")
        if not self.iocs:
            lines.append("_No high-confidence IOCs identified._\n")
        else:
            for ioc_type, values in self.iocs.items():
                lines.append(f"### {ioc_type}")
                for v in sorted(values):
                    lines.append(f"- `{v}`")
                lines.append("")
        
        # Behavioral Section
        lines.append("## Behavioral Findings\n")
        for section, items in self.behaviors.items():
            lines.append(f"### {section} Behavior")
            for i in sorted(set(items)):
                lines.append(f"- {i}")
            lines.append("")

        # Hard IOCs Section
        lines.append("## Indicators of Compromise (IOCs)\n")
        lines.append("### Hard IOCs (Reusable)\n")
        if not self.hard_iocs:
            lines.append("_No hard IOCs identified._\n")
        else:
            for k, vals in self.hard_iocs.items():
                lines.append(f"**{k}**")
                for v in sorted(vals):
                    lines.append(f"- `{v}`")
                lines.append("")

        # Soft IOCs Section
        lines.append("### Soft IOCs (Case-derived)\n")
        if not self.soft_iocs:
            lines.append("_No soft IOCs identified._\n")
        else:
            for k, vals in self.soft_iocs.items():
                lines.append(f"**{k}**")
                for v in sorted(vals):
                    lines.append(f"- `{v}`")
                lines.append("")
        
        # Environmental & Benign Section
        lines.append("## Environmental & Benign Artifacts\n")
        if not self.environmental:
            lines.append("_None observed._\n")
        else:
            for v in sorted(self.environmental):
                lines.append(f"- `{v}`")
        lines.append("")
        
        lines.append("## Case Assessment\n")
        lines.append(f"**Overall Severity:** {case_score['severity']}")
        lines.append(f"**Confidence Level:** {case_score['confidence']}\n")

        lines.append("**Assessment Rationale:**")
        for r in case_score["rationale"]:
            lines.append(f"- {r}")
        lines.append("")

        # Notes
        lines.append("## Notes & Limitations\n")
        lines.append(
            "- Network activity may not be fully observable for short-lived or "
            "failed connection attempts.\n"
            "- Filesystem and registry findings are based on snapshot diffing.\n"
            "- This report reflects observed behavior, not intent attribution.\n"
        )

        return "\n".join(lines)

    # --------------------------------------------------
    # RUN ALL
    # --------------------------------------------------
    def build(self):
        self.load_evidence()
        self.build_timeline()
        self.extract_findings()
        return self.render()

